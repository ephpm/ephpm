fn escape_toml(path: &Path) -> String {
    let mut out = String::new();
    for ch in path.to_string_lossy().chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

/// Value of the first unlabeled Prometheus series named exactly `name`.
fn parse_metric(text: &str, name: &str) -> Option<f64> {
    text.lines()
        .filter(|l| !l.starts_with('#'))
        .find(|l| l.split_whitespace().next() == Some(name))
        .and_then(|l| l.split_whitespace().last())
        .and_then(|v| v.parse().ok())
}

/// First column of the first statement's result rows, as strings.
fn first_column(v: &serde_json::Value) -> Vec<String> {
    let Some(rows) = v["results"][0]["response"]["result"]["rows"].as_array() else {
        return Vec::new();
    };
    rows.iter()
        .map(|row| {
            let cell = &row[0];
            cell["value"]
                .as_str()
                .map_or_else(|| cell["value"].to_string(), std::string::ToString::to_string)
        })
        .collect()
}

#[allow(clippy::cast_precision_loss)]
fn to_f64(n: usize) -> f64 {
    n as f64
}

