    /// The property the backup relies on: `VACUUM INTO` of a live database
    /// — serving factory open, a writer committing concurrently, a trigger
    /// in the schema — yields a self-contained file that passes
    /// `integrity_check` and still carries the trigger and the rows.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn vacuum_into_of_a_live_database_is_consistent_and_carries_triggers() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("live.db");
        let serving = wal_gate::builder_with_gate(Turso::builder(path.to_str().unwrap()))
            .build()
            .await
            .unwrap();
        let conn = serving.raw_connection().unwrap();
        exec(&conn, "CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)").await;
        exec(&conn, "CREATE TABLE log (id INTEGER)").await;
        exec(
            &conn,
            "CREATE TRIGGER t_ai AFTER INSERT ON t BEGIN INSERT INTO log VALUES (new.id); END",
        )
        .await;
        for i in 0..200 {
            exec(&conn, &format!("INSERT INTO t (v) VALUES ('row {i}')")).await;
        }
        let before = count(&conn, "SELECT COUNT(*) FROM t").await;
        assert_eq!(before, 200);

        // A writer that keeps committing while the snapshot runs.
        let writer_conn = serving.raw_connection().unwrap();
        let stop = Arc::new(std::sync::atomic::AtomicBool::new(false));
        let writer = {
            let stop = Arc::clone(&stop);
            tokio::spawn(async move {
                let mut n = 0u32;
                while !stop.load(std::sync::atomic::Ordering::Relaxed) {
                    exec(&writer_conn, &format!("INSERT INTO t (v) VALUES ('late {n}')")).await;
                    n += 1;
                    tokio::task::yield_now().await;
                }
                n
            })
        };

        let dest = dir.path().join("snap.db");
        snapshot_into(&path, &dest).await.expect("VACUUM INTO on a live database");
        stop.store(true, std::sync::atomic::Ordering::Relaxed);
        let written = writer.await.unwrap();
        assert!(written > 0, "the concurrent writer must have run");
        // A second snapshot into an existing path is refused by the engine,
        // surfaced rather than worked around.
        assert!(snapshot_into(&path, &dest).await.is_err());

        // The source is unharmed: every row ever written is there.
        let total = count(&conn, "SELECT COUNT(*) FROM t").await;
        assert_eq!(total, 200 + i64::from(written));
        drop(conn);
        drop(serving);

        // The artifact: self-contained, intact, trigger included, rows
        // from a consistent read view (at least the 200 committed before).
        assert!(!dest.with_extension("db-wal").exists(), "no -wal sidecar left");
        let snap = turso::Builder::new_local(dest.to_str().unwrap()).build().await.unwrap();
        let sconn = snap.connect().unwrap();
        let mut rows = sconn.query("PRAGMA integrity_check", ()).await.unwrap();
        let row = rows.next().await.unwrap().unwrap();
        assert_eq!(row.get_value(0).unwrap(), turso::Value::Text("ok".into()));
        drop(rows);
        assert_eq!(
            count(&sconn, "SELECT COUNT(*) FROM sqlite_master WHERE type = 'trigger'").await,
            1,
            "the trigger ships with the backup"
        );
        let in_snapshot = count(&sconn, "SELECT COUNT(*) FROM t").await;
        assert!(in_snapshot >= 200 && in_snapshot <= total, "{in_snapshot}");
        assert_eq!(
            count(&sconn, "SELECT COUNT(*) FROM log").await,
            in_snapshot,
            "the trigger's rows are consistent with the table's"
        );
        // And the trigger still fires in the restored copy.
        exec(&sconn, "INSERT INTO t (v) VALUES ('restored')").await;
        assert_eq!(count(&sconn, "SELECT COUNT(*) FROM log").await, in_snapshot + 1);
    }

    /// Every row of `sql`, each column rendered through `quote()`, so two
    /// databases can be compared value by value.
    async fn dump(conn: &turso::Connection, sql: &str) -> Vec<Vec<String>> {
        let mut rows = conn.query(sql, ()).await.unwrap_or_else(|e| panic!("{sql}: {e}"));
        let mut out = Vec::new();
        while let Some(row) = rows.next().await.unwrap() {
            out.push(
                (0..row.column_count())
                    .map(|i| format!("{:?}", row.get_value(i).unwrap()))
                    .collect(),
            );
        }
        out
    }

    /// The copy carries what the engine's `VACUUM INTO` carried: every
    /// schema object verbatim (tables of each rowid flavour, indexes, a
    /// view, a trigger), every row with its rowid, the AUTOINCREMENT
    /// counter *as recorded* (not as implied by the surviving rows), the
    /// header cookies and the page size — and nothing fires during the
    /// copy.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn snapshot_carries_the_schema_rows_rowids_and_counters_faithfully() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("src.db");
        let db = turso::Builder::new_local(path.to_str().unwrap()).build().await.unwrap();
        let conn = db.connect().unwrap();
        for sql in [
            "PRAGMA user_version = 42",
            "PRAGMA application_id = 7",
            // INTEGER PRIMARY KEY: the column is the rowid.
            "CREATE TABLE alias (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT, b BLOB, r REAL, n INTEGER)",
            // A plain rowid table: the hidden rowid must survive, gaps and all.
            // (WITHOUT ROWID is flag-gated experimental in the pinned engine;
            // its column rule is covered by `copy_column_lists_follow_the_engine_rules`.)
            "CREATE TABLE plain (k TEXT NOT NULL, v TEXT)",
            // A composite PK on a rowid table (no alias), odd identifiers.
            "CREATE TABLE \"odd \"\"name\"\"\" (\"col a\" INTEGER, \"col\"\"b\" TEXT, PRIMARY KEY (\"col a\", \"col\"\"b\"))",
            "CREATE TABLE log (what TEXT)",
            "CREATE INDEX plain_k ON plain (k)",
            "CREATE UNIQUE INDEX alias_v ON alias (v)",
            "CREATE VIEW plain_view AS SELECT k FROM plain WHERE v IS NOT NULL",
            "CREATE TRIGGER alias_ai AFTER INSERT ON alias BEGIN INSERT INTO log VALUES ('fired'); END",
            "INSERT INTO alias (v, b, r, n) VALUES ('one', x'0102', 1.5, NULL)",
            "INSERT INTO alias (v, b, r, n) VALUES ('two', NULL, -2.25, 7)",
            "INSERT INTO alias (v, b, r, n) VALUES ('three', x'', 0.0, 0)",
            // The counter keeps 3 even though row 3 is gone.
            "DELETE FROM alias WHERE id = 3",
            "INSERT INTO plain (rowid, k, v) VALUES (10, 'a', 'x')",
            "INSERT INTO plain (rowid, k, v) VALUES (20, 'b', NULL)",
            "INSERT INTO plain (rowid, k, v) VALUES (35, 'c', 'z')",
            "INSERT INTO \"odd \"\"name\"\"\" VALUES (1, 'x'), (2, 'y')",
            "DELETE FROM log",
        ] {
            exec(&conn, sql).await;
        }
        assert_eq!(count(&conn, "SELECT seq FROM sqlite_sequence WHERE name = 'alias'").await, 3);

        let dest = dir.path().join("snap.db");
        snapshot_into(&path, &dest).await.expect("snapshot");
        assert!(!dest.with_extension("db-wal").exists(), "no -wal sidecar left");

        let snap = turso::Builder::new_local(dest.to_str().unwrap()).build().await.unwrap();
        let sconn = snap.connect().unwrap();
        let mut rows = sconn.query("PRAGMA integrity_check", ()).await.unwrap();
        let row = rows.next().await.unwrap().unwrap();
        assert_eq!(row.get_value(0).unwrap(), turso::Value::Text("ok".into()));
        drop(rows);

        // Schema: every user object, verbatim, in the same order.
        let schema_sql = "SELECT type, name, tbl_name, sql FROM sqlite_schema \
                          WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid";
        assert_eq!(dump(&sconn, schema_sql).await, dump(&conn, schema_sql).await);
        // Rows, with rowids.
        for sql in [
            "SELECT rowid, id, v, b, r, n FROM alias ORDER BY rowid",
            "SELECT rowid, k, v FROM plain ORDER BY rowid",
            "SELECT rowid, \"col a\", \"col\"\"b\" FROM \"odd \"\"name\"\"\" ORDER BY rowid",
            "SELECT k FROM plain_view ORDER BY k",
        ] {
            assert_eq!(dump(&sconn, sql).await, dump(&conn, sql).await, "{sql}");
        }
        assert_eq!(
            dump(&sconn, "SELECT rowid FROM plain ORDER BY rowid").await,
            [["Integer(10)"], ["Integer(20)"], ["Integer(35)"]]
        );
        // The trigger did not fire during the copy, and still works after.
        assert_eq!(count(&sconn, "SELECT COUNT(*) FROM log").await, 0);
        exec(&sconn, "INSERT INTO alias (v) VALUES ('four')").await;
        assert_eq!(count(&sconn, "SELECT COUNT(*) FROM log").await, 1);
        // The AUTOINCREMENT counter was carried as recorded: the new row got id 4, not 3.
        assert_eq!(count(&sconn, "SELECT id FROM alias WHERE v = 'four'").await, 4);
        // Header cookies and page size.
        assert_eq!(count(&sconn, "PRAGMA user_version").await, 42);
        assert_eq!(count(&sconn, "PRAGMA application_id").await, 7);
        assert_eq!(count(&sconn, "PRAGMA page_size").await, count(&conn, "PRAGMA page_size").await);
        // The source read view was released: it can still be written.
        exec(&conn, "INSERT INTO plain (k) VALUES ('after')").await;
    }

    /// A table whose columns shadow every rowid pseudo-name copies its rows
    /// (rowids renumber — the hidden rowid cannot be named in SQL).
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn snapshot_copies_a_table_that_shadows_the_rowid_names() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("src.db");
        let db = turso::Builder::new_local(path.to_str().unwrap()).build().await.unwrap();
        let conn = db.connect().unwrap();
        exec(&conn, "CREATE TABLE shadow (rowid TEXT, _rowid_ TEXT, oid TEXT)").await;
        exec(&conn, "INSERT INTO shadow VALUES ('a', 'b', 'c'), ('d', 'e', 'f')").await;
        let dest = dir.path().join("snap.db");
        snapshot_into(&path, &dest).await.expect("snapshot");
        let snap = turso::Builder::new_local(dest.to_str().unwrap()).build().await.unwrap();
        let sconn = snap.connect().unwrap();
        let sql = "SELECT \"rowid\", \"_rowid_\", \"oid\" FROM shadow ORDER BY 1";
        assert_eq!(dump(&sconn, sql).await, dump(&conn, sql).await);
    }

    /// `VmHWM` of this process in MB (Linux only).
    #[cfg(target_os = "linux")]
    fn vm_hwm_mb() -> u64 {
        let status = std::fs::read_to_string("/proc/self/status").unwrap();
        let line = status.lines().find(|l| l.starts_with("VmHWM:")).unwrap();
        line.split_whitespace().nth(1).unwrap().parse::<u64>().unwrap() / 1024
    }

    /// The property this module exists to keep: snapshotting a database
    /// costs a bounded amount of resident memory, not a multiple of its
    /// size. A 96 MB database is copied and the process high-water mark may
    /// grow by at most [`SNAPSHOT_MEMORY_BOUND_MB`]; the engine's
    /// `VACUUM INTO` grew it by ~2× the file (about 200 MB here, 1.4 GB
    /// for a 688 MB file, measured with `examples/db_backup_memtest.rs`).
    /// Ignored by default (it writes ~200 MB and takes a while unoptimised);
    /// the nightly linked suite runs ignored tests, one process each.
    #[cfg(target_os = "linux")]
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    #[ignore = "writes ~200 MB; run deliberately or in the nightly suite"]
    async fn snapshot_memory_is_bounded_regardless_of_database_size() {
        const SNAPSHOT_MEMORY_BOUND_MB: u64 = 64;
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("big.db");
        let db = turso::Builder::new_local(path.to_str().unwrap()).build().await.unwrap();
        let conn = db.connect().unwrap();
        exec(&conn, "CREATE TABLE t (id INTEGER PRIMARY KEY, k TEXT, v BLOB)").await;
        exec(&conn, "CREATE INDEX t_k ON t (k)").await;
        let mut insert = conn.prepare("INSERT INTO t (k, v) VALUES (?, ?)").await.unwrap();
        let mut rng = 0x9E37_79B9_7F4A_7C15_u64;
        let mut payload = vec![0u8; 1000];
        for i in 0..96_000u32 {
            if i % 1000 == 0 {
                exec(&conn, "BEGIN").await;
            }
            for byte in &mut payload {
                rng ^= rng << 13;
                rng ^= rng >> 7;
                rng ^= rng << 17;
                *byte = (rng & 0xff) as u8;
            }
            insert.execute((format!("key-{i:08}"), payload.clone())).await.unwrap();
            if i % 1000 == 999 {
                exec(&conn, "COMMIT").await;
            }
        }
        // (`query`, not `execute`: the pragma answers with a row.)
        let _ = count(&conn, "PRAGMA wal_checkpoint(TRUNCATE)").await;
        drop(insert);
        drop(conn);
        drop(db);
        let size_mb = std::fs::metadata(&path).unwrap().len() / (1024 * 1024);
        assert!(size_mb >= 96, "fixture is {size_mb} MB");

        let before = vm_hwm_mb();
        let dest = dir.path().join("snap.db");
        snapshot_into(&path, &dest).await.expect("snapshot");
        let after = vm_hwm_mb();
        let grown = after.saturating_sub(before);
        eprintln!("database {size_mb} MB; VmHWM {before} MB -> {after} MB (+{grown} MB)");
        assert!(
            grown <= SNAPSHOT_MEMORY_BOUND_MB,
            "snapshotting a {size_mb} MB database grew the high-water mark by {grown} MB (bound {SNAPSHOT_MEMORY_BOUND_MB} MB)"
        );
        // The copy is the same data, packed by a fresh build (within 10 %).
        let copy_mb = std::fs::metadata(&dest).unwrap().len() / (1024 * 1024);
        assert!(copy_mb.abs_diff(size_mb) <= size_mb / 10, "copy is {copy_mb} MB for {size_mb} MB");
    }

    #[test]
    fn copy_column_lists_follow_the_engine_rules() {
        let col = |name: &str, declared_type: &str, pk: i64| TableColumn {
            name: name.to_owned(),
            declared_type: declared_type.to_owned(),
            pk,
        };
        // INTEGER PRIMARY KEY is copied as the rowid, not as data.
        let cols = [col("id", "INTEGER", 1), col("v", "TEXT", 0)];
        assert_eq!(copy_column_list(&cols, "CREATE TABLE t (...)").unwrap(), ["rowid", "v"]);
        // INT PRIMARY KEY is not an alias; the hidden rowid is copied too.
        let cols = [col("id", "INT", 1), col("v", "TEXT", 0)];
        assert_eq!(copy_column_list(&cols, "CREATE TABLE t (...)").unwrap(), ["rowid", "id", "v"]);
        // A composite PK is not an alias either.
        let cols = [col("a", "INTEGER", 1), col("b", "INTEGER", 2)];
        assert_eq!(copy_column_list(&cols, "CREATE TABLE t (...)").unwrap(), ["rowid", "a", "b"]);
        // WITHOUT ROWID: data columns only.
        let cols = [col("a", "TEXT", 1), col("b", "INTEGER", 2)];
        assert_eq!(
            copy_column_list(&cols, "create table t (a, b, primary key (a, b)) without\n  rowid")
                .unwrap(),
            ["a", "b"]
        );
        // The first unshadowed pseudo-name is used; all shadowed means None.
        let cols = [col("rowid", "TEXT", 0), col("v", "TEXT", 0)];
        assert_eq!(
            copy_column_list(&cols, "CREATE TABLE t (...)").unwrap(),
            ["_rowid_", "rowid", "v"]
        );
        let cols = [col("rowid", "TEXT", 0), col("_rowid_", "TEXT", 0), col("OID", "TEXT", 0)];
        assert!(copy_column_list(&cols, "CREATE TABLE t (...)").is_none());
        assert_eq!(quote_ident("odd \"name\""), "\"odd \"\"name\"\"\"");
    }
